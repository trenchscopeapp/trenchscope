/** Glyph width and height in font pixels. */
export const FONT_W = 5;
export const FONT_H = 9;

// Small 3×5 digits for subscripts (₀-₉: the price formatter's zero-count, e.g. $0.0₅3105) and superscripts (⁰-⁹).
// A subscript must never render as a full-size digit: that would turn 0.0₅31 into 0.0531.
const SMALL: string[][] = [
  ['###', '#.#', '#.#', '#.#', '###'], ['.#.', '##.', '.#.', '.#.', '###'], ['###', '..#', '###', '#..', '###'],
  ['###', '..#', '.##', '..#', '###'], ['#.#', '#.#', '###', '..#', '..#'], ['###', '#..', '###', '..#', '###'],
  ['###', '#..', '###', '#.#', '###'], ['###', '..#', '.#.', '.#.', '.#.'], ['###', '#.#', '###', '#.#', '###'],
  ['###', '#.#', '###', '..#', '###'],
];
const SUB = '₀₁₂₃₄₅₆₇₈₉', SUP = '⁰¹²³⁴⁵⁶⁷⁸⁹';
for (let d = 0; d < 10; d++) {
  const rows = SMALL[d].map((r) => `.${r}.`);
  G[SUB[d]] = ['.....', '.....', '.....', '.....', ...rows];
  G[SUP[d]] = rows;
}

const BITS = new Map<string, Uint8Array>();
for (const [ch, rows] of Object.entries(G)) {
  const b = new Uint8Array(FONT_W * FONT_H);
  rows.forEach((r, y) => { for (let x = 0; x < FONT_W; x++) if (r[x] === '#') b[y * FONT_W + x] = 1; });
  BITS.set(ch, b);
}

/** The 5×9 bitmap for a character (1 = ink), or null when the font has no glyph for it. */
export function glyphBits(ch: string): Uint8Array | null {
  return BITS.get(ch) ?? null;
}

/** Every character with a bitmap glyph (tests check the printable ASCII range is complete). */
export function fontChars(): string[] { return [...BITS.keys()]; }
